"""접속 표시(presence) 쓰기 스로틀 (PLAN Phase 4 — 스케일 심).

**문제.** 놀이 방 화면은 1.2초마다, 채팅은 그보다 조금 느리게 폴링한다. 폴링마다 멤버 행의
`last_seen` 을 갱신하면 **읽기 요청이 그대로 쓰기 요청이 된다**. SQLite 는 쓰기를 직렬화하므로
(WAL 이어도 writer 는 하나다) 사람이 늘수록 아무도 아무것도 안 하는 동안에도 쓰기 큐가 찬다.
예전 임계값은 2초였는데, 그건 1.2초 폴링에 대해 "두 번에 한 번은 쓴다"는 뜻이라 사실상
스로틀이 아니었다.

**해법.** 30초. 재접속 감지(`active=False → True`)는 **즉시** 해야 하므로 스로틀에서 뺀다 —
느려도 되는 것은 '아직 여기 있다'는 갱신뿐이다.

**왜 30초가 안전한가.** 소비하는 쪽의 임계값이 훨씬 크다:
  * 놀이의 접속자 판정 `PRESENCE_SECONDS = 90`
  * 채팅 온라인 점(계획 F)은 **2분 이상**으로 정한다
30초마다 갱신하면 90초·120초 창 안에 최소 두세 번은 찍히므로, 실제로 붙어 있는 사람이
'오프라인'으로 깜빡이지 않는다. 스로틀을 이 두 값에 가깝게 올리면 그 순간 깜빡이기 시작한다 —
이 파일과 소비자 임계값은 **함께** 봐야 한다.

## 유휴(idle) — 퇴근한 사람이 '접속 중'으로 남던 문제 (X12)

**증상.** 모니터만 끄고 간 사람은 탭이 여전히 보이는 상태다. 브라우저는 그 탭의 폴링을
멈추지 않고, 폴링이 도는 동안 `last_seen` 이 계속 갱신되어 **밤새 초록 점이 켜져 있었다.**
동료는 그 점을 보고 말을 걸고, 답은 다음 날 아침에 온다.

**가시성으로는 못 고친다.** `document.hidden` 은 '탭이 가려졌는가' 만 안다. 모니터 전원,
화면 잠금, 자리 비움은 전부 탭이 보이는 상태다(감사가 확인한 그대로다). 다만 탭이 숨는
경우는 라이브러리가 이미 폴링을 멈춘다(`refetchIntervalInBackground` 기본값 false) —
그래서 남은 구멍이 정확히 '탭은 보이는데 사람은 없다' 하나다.

**그래서 신호를 사람의 입력으로 잡는다.** 판정은 브라우저에서 하고(그쪽에만 입력이 있다)
서버는 그 결론을 `idle` 로 받는다. 어떤 입력을, 왜 그것으로 골랐는지는
`frontend/src/lib/idle.js` 에 적어 뒀다 — 두 파일은 **짝**이다.

**서버가 하는 일은 한 가지뿐이다: 유휴면 `last_seen` 을 쓰지 않는다.** 지우지도, 과거로
되돌리지도 않는다. 그러면 온라인 창(채팅 120초)이 지나면서 점이 저절로 꺼지고, 사람이
돌아와 한 번만 움직이면 다음 폴링에서 즉시 다시 켜진다(그 시점 `last_seen` 은 이미
30초보다 오래돼 스로틀에 걸리지 않는다).

⚠️ **놀이(app/games)에는 걸지 않는다.** 거기서 `last_seen` 은 표시가 아니라 **추첨 대상
풀**을 가른다(`_present_players`). 사다리 결과를 기다리며 화면만 보고 있는 사람은 입력이
없다 — 유휴로 잡으면 그 사람이 추첨에서 조용히 빠진다. 같은 신호라도 소비하는 쪽이 다르면
답도 달라진다.
"""

from __future__ import annotations

from datetime import datetime

# 여기 한 곳에서만 정의한다. 놀이·채팅이 각자 숫자를 들고 있으면 한쪽만 조정되어
# '채팅에서는 온라인인데 놀이에서는 오프라인'인 상태가 생긴다.
PRESENCE_THROTTLE_SECONDS = 30.0


def should_touch(last_seen: datetime | None, now: datetime, *, idle: bool = False) -> bool:
    """`last_seen` 을 다시 쓸 때가 됐는가.

    `idle=True` 면 무조건 쓰지 않는다 — 폴링은 돌지만 사람은 없다는 뜻이라, 그 폴링을
    '아직 여기 있다'로 기록하면 그게 바로 X12 의 거짓말이다. 처음 보는 멤버(`last_seen`
    이 None)에게도 마찬가지다: 한 번도 움직인 적 없는 사람을 '접속 중'으로 켜지 않는다.

    `last_seen` 이 없으면(처음 보는 멤버) 무조건 쓴다. 시계가 뒤로 간 경우(음수 경과)도
    쓴다 — 안 쓰면 시계가 정상으로 돌아올 때까지 영원히 스로틀에 걸린다.
    """
    if idle:
        return False
    if last_seen is None:
        return True
    elapsed = (now - last_seen).total_seconds()
    return elapsed < 0 or elapsed >= PRESENCE_THROTTLE_SECONDS
