"""백업이 무엇을 담고 무엇을 일부러 안 담는가 (S12 · D-204 · D-203).

## 「전부 담는다」는 정책이 아니다

`pg_dump` 를 옵션 없이 돌리면 데이터베이스에 있는 모든 것이 들어온다. 그것은 편하지만
정책이 아니라 **정책의 부재**다. 이 파일이 없으면 두 가지가 조용히 나빠진다.

1. **파생 데이터가 백업을 지배한다.** `document_chunks` 는 문서 하나당 수십 행이고
   행마다 384차 벡터를 든다. 원본 문서보다 크고, 그런데 **원본에서 언제든 다시 만들
   수 있다**(D-203). 되돌릴 수 없는 것을 지키려고 만든 파일이 되돌릴 필요가 없는
   것으로 채워진다.
2. **무엇을 잃었는지 말할 수 없다.** 복원한 사람이 「검색이 비어 있는데 이게 정상인가」를
   물었을 때, 그 답이 코드 어딘가의 `--exclude-table-data` 한 줄에만 있으면 아무도
   답하지 못한다. 그래서 이 목록은 **매니페스트에 그대로 실려** 백업과 함께 이동한다.

## 「제외」는 표를 빼는 것이 아니라 **행**을 빼는 것이다

`--exclude-table-data` 를 쓴다(`--exclude-table` 이 아니다). 표는 그대로 서고 행만 비운다.
표까지 빼면 복원본의 스키마가 코드가 기대하는 모양과 달라져 6단계(`alembic_version` 대조)가
통과하는데 7단계(앱 기동)가 죽는다 — 가장 늦게, 가장 알아보기 어려운 자리에서.

## 비운 자리는 **스스로 다시 찬다**

넷 다 재생성 경로가 이미 제품 안에 있고, 그 경로는 「행이 없다」를 신호로 읽는다.

| 표 | 누가 다시 만드는가 |
|---|---|
| `ai_index_state` | 색인 레인의 훑기가 상태 행이 없는 문서를 전부 찾는다 (S9) |
| `document_chunks` | 위 색인이 만든다. `ai_index_state` 를 함께 비우는 이유가 이것이다 |
| `search_documents` | `app/search/indexer.py::reindex_all` 이 주기적으로 전체 재구축한다 |
| `rate_limit_buckets` | 다음 요청이 만든다. 남기면 **복원 시점의 스로틀 상태**가 되살아난다 |

`ai_index_state` 만 비우고 `document_chunks` 를 남기면 최악이다 — 색인은 처음부터 다시
도는데 옛 chunk 가 그대로 남아 같은 문단이 두 번 검색된다.
"""

from __future__ import annotations

# ── 정본: 반드시 담는다 ──────────────────────────────────────────────────────
#
# 화면과 매니페스트가 함께 읽는 문장이다. 표 이름이 아니라 **사람이 아는 이름**으로
# 적는다 — 복원을 결정하는 사람이 표 이름을 알 이유가 없다.
INCLUDED_SCOPE: tuple[str, ...] = (
    "PostgreSQL 데이터베이스 전체",
    "업로드 원본 파일과 첨부",
    "설정",
    "감사 로그",
)

# ── 재생성 가능: 일부러 안 담는다 ────────────────────────────────────────────
#
# `(표, 사람이 읽는 이름, 누가 다시 만드는가)`. 매니페스트가 이 셋을 그대로 싣는다.
EXCLUDED_TABLE_DATA: tuple[tuple[str, str, str], ...] = (
    (
        "document_chunks",
        "AI 색인 조각과 임베딩",
        "색인 레인이 문서 원본에서 다시 만듭니다.",
    ),
    (
        "ai_index_state",
        "AI 색인 진행 상태",
        "상태 행이 없는 문서를 색인 레인이 스스로 찾아 다시 돕니다.",
    ),
    (
        "search_documents",
        "검색 색인",
        "검색 색인 갱신이 원본에서 전체를 다시 만듭니다.",
    ),
    (
        "rate_limit_buckets",
        "요청 제한 카운터",
        "다음 요청이 다시 만듭니다.",
    ),
)


def excluded_tables() -> tuple[str, ...]:
    """`pg_dump --exclude-table-data` 에 넘길 표 이름."""
    return tuple(table for table, _label, _who in EXCLUDED_TABLE_DATA)


def scope_manifest() -> dict:
    """매니페스트에 실리는 범위 절. **백업과 함께 이동한다.**

    복원하는 사람이 이 백업 하나만 들고 있어도 「무엇이 안 담겼고 그것이 어떻게 다시
    차는가」를 읽을 수 있어야 한다. 그 답이 저장소의 코드에만 있으면, 저장소가 없는
    날에는 답이 없다.
    """
    return {
        "included": list(INCLUDED_SCOPE),
        "excluded_table_data": [
            {"table": table, "label": label, "regenerated_by": who}
            for table, label, who in EXCLUDED_TABLE_DATA
        ],
        "note": (
            "제외한 것은 표가 아니라 행입니다. 표는 그대로 복원되고 비어 있으며, "
            "제품이 원본에서 다시 채웁니다."
        ),
    }
