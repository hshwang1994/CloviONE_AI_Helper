/* 값별 배지 색 매핑 — **상태에만 남는다** (지시 11).
 *
 * ## 무엇이 문제였나
 *
 * 이 파일은 원래 셋을 함께 다뤘다: 게시판 카테고리, 문서 종류, 제안 상태. 셋 다 `Badge`
 * 였고 값마다 다른 의미색을 받았다. 그래서 화면에서 이런 일이 벌어졌다.
 *
 *   · `"공지": "danger"` — 카테고리 하나가 **빨간 알약**이 됐다. 빨강은 이 앱에서 "오류"다.
 *   · `"맛집": "warn"` — 주황은 "조치 필요"다. 점심 메뉴 글이 조치 필요로 보였다.
 *   · 문서 종류 여덟 가지가 각자 다른 색을 가져가, 목록 한 줄에 의미 없는 색이 둘씩 떴다.
 *
 * 색 어휘는 예산이다. 분류가 그것을 다 쓰면 정작 상태가 말할 색이 남지 않는다
 * (D-141 "채도 예산은 데이터에 쓴다").
 *
 * ## 지금 규칙
 *
 *   **상태**(지금 무슨 일이 벌어지는가) → `Badge`. 표지 + 글자 + 의미색.
 *   **분류**(이것이 무엇인가)          → `Tag`. 중립 칩. 색으로 등급을 매기지 않는다.
 *
 * 그래서 이 파일에는 제안 상태만 남는다. 카테고리·문서 종류·업무 분야·고정 여부는 호출부가
 * `Tag` 를 직접 쓴다 — 색 표가 필요 없어졌다는 것이 곧 그 판정의 결과다.
 */

/* 제안 상태 색. 일이 흘러가는 방향을 색으로도 읽게 한다: 아직 아무도 안 본 것(회색) →
 * 보는 중(파랑) → 하는 중(주황) → 끝(초록) → 멈춤(빨강). '보류'만 빨강인 이유는 그것만
 * 사람이 다시 손대야 풀리는 상태이기 때문이다. */
const IDEA_STATUS_KIND = {
  "제안": "neutral",
  "검토중": "info",
  "진행": "warn",
  "완료": "ok",
  "보류": "danger",
};

export function ideaStatusKind(status) {
  return IDEA_STATUS_KIND[status] || "neutral";
}
