// DataScreen.jsx finishAction()과 SubListDrawer.jsx act()가 공유하는 조회 함수 — 두 곳이 각자
// "라벨 + 완료"를 다시 손으로 반복하면(예전이 그랬다) 한쪽만 고쳐지고 다시 갈라진다.
export function successMessageFor(label) {
  const cleaned = (label || "").replace(/^\+\s*/, "");
  return ACTION_SUCCESS_MESSAGES[cleaned] || GENERIC_SUCCESS_MESSAGE;
}
