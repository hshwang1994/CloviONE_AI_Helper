/* 액션 기본 성공 토스트 문구 사전 (PA-RC-0025).
 *
 * DataScreen.jsx의 finishAction()과 SubListDrawer.jsx의 act()는 액션이 자기만의 결과 메시지를
 * 정의하지 않으면(a.result가 없으면) 이 사전에서 라벨로 문장을 찾는다. 예전엔 두 곳 모두
 * `라벨 + " 완료"`로 문자열을 이어 붙였다 — "삭제" 액션이면 "삭제 완료"가 떴다. 이건 명사형
 * 배지처럼 읽히고 마침표도 없어 docs/UX_WRITING.md §2(문장형은 마침표)와 어긋났다. 같은 화면
 * (/departments)의 다른 액션은 이미 옳았다: 추가 → "추가했습니다.", 수정 → "저장했습니다." —
 * 삭제만 이 기본 경로를 타서 혼자 어긋나 있었다.
 *
 * 라벨 텍스트를 기계적으로 이어 붙여 동사를 만들지 않는다 — 이 저장소에는 "보관 복구"·"세션
 * 해제"(UsersBulk.jsx/Users.jsx, 이 파일과는 별개의 자체 처리 경로)처럼 라벨 자체가 이미 명사
 * 복합어라 `라벨 + "했습니다."`로 이어 붙이면 자연스러운 문장이 안 나오는 경우가 있다. 그래서
 * 이 표는 라벨마다 손으로 확인해 적은 사전이다 — 라벨 문자열을 파싱해서 동사를 추론하지 않는다.
 *
 * 사전에 없는 라벨(새로 추가된 액션)은 GENERIC_SUCCESS_MESSAGE로 떨어진다 — 옛 "라벨 완료"
 * 패턴으로 돌아가지 않으면서도 여전히 문장형이다. scripts/check_success_toast_labels.py가
 * registry/*.js를 전수 스캔해서, a.result()로 자기 메시지를 정의하지 않는(=이 기본 경로를 타는)
 * 새 라벨이 이 사전에 없으면 정적 검사에서 실패시킨다(등록을 강제한다) — docs/UX_WRITING.md §3의
 * 표준 동사표와 같은 이유: 표만 두면 다음 화면이 그 표를 안 보고 다시 흩어진다.
 *
 * a.result(res)로 이미 자기 메시지를 만드는 액션(예: '지금 실행', '헬스체크', /users의 대량
 * 활성화)은 이 사전과 무관하다 — finishAction()이 a.result가 있으면 이 기본 경로 자체를
 * 타지 않는다. 이 사전은 그 opt-out 경로를 덮어쓰지 않는다.
 */

